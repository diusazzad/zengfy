    {
        $data = $this->getNGOData();

        return response()->json([
            'status' => 'success',
            'code' => 200,
            'data' => $data,
        ], 200, [
            'Cache-Control' => 'max-age=300, public, stale-while-revalidate=86400',
        ]);
    }
