     * Web Entrypoint for Zengfy NGO Product Landing.
     */
    public function index(Request $request): View
    {
        $initialData = $this->getNGOData();

        return view('ngo::landing', compact('initialData'));
    }

    /**
     * Public REST API endpoint for NGO Landing data.
     */
