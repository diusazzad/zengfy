    {
        $data = $this->getSkillData();

        return response()->json([
            'status' => 'success',
            'timestamp' => now()->toIso8601String(),
            'data' => $data,
        ], 200, [
            'Cache-Control' => 'public, max-age=300, stale-while-revalidate=86400',
